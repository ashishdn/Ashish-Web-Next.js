// Helper to get all thanas for a district
export function getThanasByDistrict(districtSlug) {
  return locations.filter((loc) => loc.districtSlug === districtSlug);
}

// Helper to get areas for a thana
export function getAreasByThana(districtSlug, thanaSlug) {
  const item = locations.find(
    (loc) => loc.districtSlug === districtSlug && loc.thanaSlug === thanaSlug
  );
  return item ? item.areas : [];
}

// Search helper for autocomplete across districts, thanas and areas
export function searchLocations(query, lang = 'bn') {
  if (!query || query.trim().length === 0) return [];
  const q = query.trim().toLowerCase();

  const results = [];

  locations.forEach((loc) => {
    // Check thana match
    const thanaBn = loc.thanaName.bn.toLowerCase();
    const thanaEn = loc.thanaName.en.toLowerCase();
    const isThanaMatch = thanaBn.includes(q) || thanaEn.includes(q);

    loc.areas.forEach((area) => {
      const areaBn = area.name.bn.toLowerCase();
      const areaEn = area.name.en.toLowerCase();
      if (isThanaMatch || areaBn.includes(q) || areaEn.includes(q)) {
        results.push({
          districtSlug: loc.districtSlug,
          thanaSlug: loc.thanaSlug,
          areaSlug: area.slug,
          thanaName: loc.thanaName[lang] || loc.thanaName.bn,
          areaName: area.name[lang] || area.name.bn,
          fullLabel: `${area.name[lang] || area.name.bn}, ${loc.thanaName[lang] || loc.thanaName.bn}`,
        });
      }
    });
  });

  return results.slice(0, 8);
}
