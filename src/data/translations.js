// Bengali digits map
const bnDigits = ['০', '১', '২', '৩', '৪', '৫', '৬', '৭', '৮', '৯'];

export function toBnNumber(val) {
  if (val === undefined || val === null) return '';
  return val
    .toString()
    .replace(/[0-9]/g, (digit) => bnDigits[parseInt(digit, 10)]);
}

export function formatBDT(amount, lang = 'bn') {
  if (amount === undefined || amount === null) return '';
  const formattedNumber = Number(amount).toLocaleString('en-IN');
  if (lang === 'bn') {
    return `৳ ${toBnNumber(formattedNumber)}`;
  }
  return `BDT ${formattedNumber}`;
}

